  async register(user: RequestUser, input: CreateOrganizationInput) {
    /*
      ── AT MOST A FEW WAITING AT ONCE, PER ACCOUNT ──────────────────────────────────
      Nothing an unapproved organization does can take money, so this is not a fraud control.
      It stops one account filling the approval queue, which buries the genuine theatre
      waiting in it. See `organization-limits.ts` for why PENDING is what counts.

      The lock is what makes the count true. Checking then inserting is a race: two
      registrations at once would both count one pending and both proceed. A transaction-
      scoped advisory lock on this account serialises them and releases itself at commit.
    */
    const org = await this.prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${registrationLockKey(user.id)}))`;
      const pending = await tx.organization.count({
        where: {
          status: OrganizationStatus.PENDING,
          members: { some: { userId: user.id, role: Role.ORGANIZER_OWNER } },
        },
      });
      if (pending >= MAX_PENDING_ORGANIZATIONS_PER_ACCOUNT) {
        throw new AppException(
          ErrorCodes.ORGANIZATION_LIMIT_REACHED,
          `You already have ${pending} organizations waiting for review. We will email you ` +
            'when they are decided, and you can register another once one of them has been.',
          HttpStatus.CONFLICT,
          { pending, limit: MAX_PENDING_ORGANIZATIONS_PER_ACCOUNT },
        );
      }
      return tx.organization.create({
        data: {
          name: input.name,
          slug: slugify(input.name),
          contactEmail: input.contactEmail,
          /*
            Recorded at registration now. The approval gate has always required a declared
            identity, and until the form asked for one, an admin's first act on every new
            organizer was to go back and ask - the platform failing its own onboarding.
            Absent is still allowed here: a seed or a support-created shell is legitimate,
            and approval is where the requirement bites.
          */
          legalName: input.legalName || null,
          legalEntityType: input.legalEntityType || null,
          registeredCountry: input.registeredCountry || null,
          taxRegistrationKind: input.taxRegistrationKind || null,
          taxRegistrationNumber: input.taxRegistrationNumber || null,
          status: OrganizationStatus.PENDING,
          members: { create: { userId: user.id, role: Role.ORGANIZER_OWNER } },
        },
      });
    });

    // Grant the platform organizer role if the user does not have it yet. Read the STORED
    // roles: `user.roles` on the request is global roles plus team-seat roles, and writing
    // that back would turn a seat in one organization into a permanent global role.
    const stored = await this.prisma.user.findUnique({
      where: { id: user.id },
      select: { roles: true },
    });
    if (stored && !stored.roles.includes(Role.ORGANIZER_OWNER)) {
      await this.prisma.user.update({
        where: { id: user.id },
        data: { roles: { set: [...new Set([...stored.roles, Role.ORGANIZER_OWNER])] } },
      });
    }

    await this.audit.record({
      actorUserId: user.id,
      organizationId: org.id,
      action: 'ORGANIZATION_CREATED',
      entityType: 'Organization',
      entityId: org.id,
    });

    /*
      Tell the admins something is waiting.

      A new organization is PENDING and cannot sell a ticket until a human approves it. The
      audit entry above recorded that it happened; nothing told anyone to look. So an
      organizer signed up, saw "awaiting approval", and waited on a queue no one had been
      paged about.

      Never throws — see AdminAudienceService. The organization is committed by this point
      and losing it to a mail outage would be far worse than a missed email.
    */
    await this.audience.notifyAdmins(
      NotificationType.ORGANIZATION_REGISTERED,
      {
        organizationId: org.id,
        organizationName: org.name,
        // A phone-only account's placeholder is not a mailbox: no contact beats a dead one.
        contactEmail: org.contactEmail ?? (isReservedEmail(user.email) ? null : user.email),
        registeredByUserId: user.id,
      },
      {
        /*
        One email per admin per hour, however many register. Each registration used to email
        every admin, so a burst of junk could spend the sending allowance — 200 a day on a
        sandboxed account — and the booking confirmations after it would not go out. The
        email says others may be waiting and points at the queue, which is the source of truth.
      */
        intentKey: registrationDigestIntent(),
      },
    );

    return org;
  }

  /**
   * The organizations the caller can work in, each carrying the caller's own role in it.
   *
   * `myRole` exists so the organizer console can stop offering actions this API will refuse:
   * without it a manager was shown Refund and check-in staff were shown Invite, and each
   * learned the rule from the error. It grants nothing — every write still checks the
   * membership itself.
   *
   * Memberships only, platform staff included. Staff used to be given every organization on
   * the platform here, with `myRole: null`, because a platform role bypassed every organization
   * check; it no longer does (see `OrgAccessService`), and staff read organizations through the
   * admin console.
   */
  async listMine(user: RequestUser) {
    const ids = await this.access.managedOrganizationIds(user);
    /*
      A SUSPENDED organization is still LISTED, so the console can say what happened instead of
      "No organization yet" - but as its name and status only. Nothing else about it is readable
      by its members while it is suspended (owner decision, 2026-10-26; see assertMember).
    */
    const suspended = await this.prisma.organizationMember.findMany({
      where: {
        userId: user.id,
        status: 'ACTIVE',
        organization: { status: OrganizationStatus.SUSPENDED },
      },
      select: {
        role: true,
        organization: { select: { id: true, name: true, slug: true, status: true } },
      },
    });
    const orgs = await this.prisma.organization.findMany({
      where: { id: { in: ids } },
      orderBy: { createdAt: 'desc' },
      /*
        `movies` is counted so the console can stop showing film navigation to organizers who do
        no film business. A COUNT, not a classification: this domain has no organization type, and
        `Cinema` cannot stand in for one - but not for the reason first written here. `Screen` is
        the room; `Cinema` is the SITE it belongs to. `Cinema` is unusable as a film signal
        because the seat-map chain is mandatory - `SeatMap.screenId` and `Screen.cinemaId` are
        both required - so any organizer who draws a seat map for ANY event creates a `Cinema`
        row. Seated events made it mean "a seated venue", not "a film business".
      */
      include: { _count: { select: { members: true, events: true, venues: true, movies: true } } },
    });
    const memberships = await this.prisma.organizationMember.findMany({
      where: { userId: user.id, status: 'ACTIVE' },
      select: { organizationId: true, role: true },
    });
    const roles = new Map(memberships.map((m) => [m.organizationId, m.role]));
    return [
      ...orgs.map((org) => ({ ...org, myRole: roles.get(org.id) ?? null })),
      ...suspended.map((m) => ({ ...m.organization, myRole: m.role })),
    ];
  }

