/**
 * Build the offline reverse-geocoding dataset from GeoNames.
 *
 *   node apps/api/scripts/build-geonames-dataset.mjs <dir with cities15000.txt + admin1CodesASCII.txt>
 *
 * Source: https://download.geonames.org/export/dump/ (cities15000.zip, admin1CodesASCII.txt),
 * licensed CC BY 4.0 - attribution in apps/api/src/discovery/geocoding/ATTRIBUTION.md.
 *
 * Output: a gzip+base64 TSV module, one row per populated place of 15,000+ people:
 *   name  ascii-name(if different)  region  country(ISO-3166 alpha-2)  lat  lng
 * Coordinates are rounded to 3 decimals (about 100 m), which is far finer than choosing a
 * city needs and keeps the module small.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('pass the directory holding the GeoNames files');
const admin1 = new Map(
  readFileSync(join(dir, 'admin1CodesASCII.txt'), 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((l) => l.split('\t'))
    .map(([code, name]) => [code, name]),
);
/*
  Not every "populated place" is a city somebody lives in. Sections of a city (PPLX - "Bay
  Street Corridor" for Toronto, "Ville-Marie" for Montreal) would be named instead of the city
  itself, and historical, abandoned or destroyed places are not anywhere anybody is.
*/
const EXCLUDED_FEATURES = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const rows = readFileSync(join(dir, 'cities15000.txt'), 'utf8')
  .split('\n')
  .filter(Boolean)
  .map((l) => l.split('\t'))
  .filter((f) => !EXCLUDED_FEATURES.has(f[7]))
  .map((f) => {
    const [, name, ascii, , lat, lng, , , cc, , a1, , , , population] = f;
    const region = admin1.get(`${cc}.${a1}`) ?? '';
    const clean = (s) => s.replace(/[\t\n]/g, ' ').trim();
    return [
      clean(name),
      ascii && ascii !== name ? clean(ascii) : '',
      clean(region),
      cc,
      Number(lat).toFixed(3),
      Number(lng).toFixed(3),
      population || '0',
    ].join('\t');
  });
const tsv = rows.join('\n');
const b64 = gzipSync(Buffer.from(tsv, 'utf8'), { level: 9 }).toString('base64');
const out = join('apps/api/src/discovery/geocoding/geonames-cities.data.ts');
writeFileSync(
  out,
  `/* eslint-disable */\n// GENERATED by apps/api/scripts/build-geonames-dataset.mjs from GeoNames (CC BY 4.0).\n// ${rows.length} places of 15,000+ people. Do not edit by hand.\nexport const GEONAMES_CITIES_GZ_B64 =\n  '${b64}';\nexport const GEONAMES_CITY_COUNT = ${rows.length};\n`,
);
console.log(`wrote ${out}: ${rows.length} cities, ${(b64.length / 1024).toFixed(0)} KB base64`);
