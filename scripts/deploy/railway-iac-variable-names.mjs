#!/usr/bin/env node
// Regenerate .railway/variables.ts: the variable NAMES (never values) each service has in each
// Railway environment. .railway/railway.ts marks every listed name preserve(), so Railway keeps
// the value it already holds.
//
// Why a list at all: Railway IaC treats a variable that is missing from a managed service as a
// deletion (proven on QA 2026-11-06: omitting `env` planned 221 variable deletions), and there
// is no "leave unlisted variables alone" option. So every name must be listed per environment.
//
// Usage (one environment at a time; RAILWAY_TOKEN = that environment's project token):
//   railway config pull --json > /tmp/graph-QA.json
//   node scripts/deploy/railway-iac-variable-names.mjs QA /tmp/graph-QA.json
// The pull is read-only. Values in the pull are `{type:"preserve"}` markers; this script
// refuses a graph that contains any real value, so a secret can never be written to source.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const [envName, graphPath] = process.argv.slice(2);
if (!['QA', 'UAT', 'PROD'].includes(envName) || !graphPath) {
  console.error('usage: railway-iac-variable-names.mjs <QA|UAT|PROD> <graph.json>');
  process.exit(2);
}
const APP_SERVICES = ['api', 'worker', 'customer-web', 'organizer-web', 'admin-web', 'db-seed'];
const graph = JSON.parse(readFileSync(graphPath, 'utf8'));
const names = {};
for (const r of graph.resources ?? []) {
  if (r.type !== 'service' || !APP_SERVICES.includes(r.name)) continue;
  const vars = r.variables ?? {};
  for (const [k, v] of Object.entries(vars)) {
    const marker = v === 'preserve' || (v && typeof v === 'object' && v.type === 'preserve');
    if (!marker) {
      console.error(
        `REFUSING: ${r.name}.${k} carries a value, not a preserve marker. Pull without --include-variables.`,
      );
      process.exit(3);
    }
  }
  names[r.name] = Object.keys(vars).sort();
}
const missing = APP_SERVICES.filter((s) => !names[s]);
if (missing.length) {
  console.error(`REFUSING: graph has no service(s) ${missing.join(', ')}`);
  process.exit(3);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const target = path.join(root, '.railway', 'variables.ts');
let all = {};
if (existsSync(target)) {
  // Load the existing file as the module it is (Node strips the `as const`). It was read with
  // JSON.parse, which broke once Prettier reformatted the file (unquoted keys, single quotes):
  // regenerating one environment then failed instead of keeping the other two.
  const mod = await import(`${pathToFileURL(target).href}?t=${Date.now()}`);
  all = JSON.parse(JSON.stringify(mod.VARIABLE_NAMES ?? {}));
}
all[envName] = names;
const ordered = Object.fromEntries(
  ['QA', 'UAT', 'PROD'].filter((e) => all[e]).map((e) => [e, all[e]]),
);
const body = `// GENERATED by scripts/deploy/railway-iac-variable-names.mjs. Variable NAMES only, never values.
// Every name here is preserve()d by railway.ts: Railway keeps the value it holds. A variable
// that exists in Railway but is missing here is a DELETION in the next plan (and needs
// --confirm-destructive). Add a new variable in Railway first, then regenerate this file.
export const VARIABLE_NAMES = ${JSON.stringify(ordered, null, 2)} as const;
`;
writeFileSync(target, body);
console.log(
  `${envName}: ${Object.entries(names)
    .map(([s, n]) => `${s}=${n.length}`)
    .join(' ')} -> ${path.relative(root, target)}`,
);
