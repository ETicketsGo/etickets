"""Regenerate the brand display face (Bricolage Grotesque) in this folder. See README.md.

usage: python make-brand-fonts.py <path to BricolageGrotesque[opsz,wdth,wght].ttf>

Needs `pip install fonttools brotli`. A separate script from make-fonts.py on purpose: that one
reproduces Google's own Inter and Plus Jakarta Sans files byte for byte, and folding a new
family into it would mean re-deriving files that are already right.

What it does differently from Google, and why:
- Width is pinned at 100 (normal). The width axis is the costliest part of the file and the
  brand never sets a condensed headline - a narrow face on a phone reads as cramped, not bold.
- Weight is limited to 500-800. The design system uses 600 and 700 for titles and 800 for the
  one hero line; nothing is set lighter in this face (Inter carries all reading text).
- Optical size (12-96) is KEPT. It is the reason this face was chosen: at 96 it is expressive
  enough for a storefront hero, at 20-30 it is calm enough for a console page title, and the
  browser picks the value from the font size on its own (`font-optical-sizing: auto`).
- Only latin and latin-ext are cut. latin-ext carries the rupee sign (U+20B9) and the
  accented capitals French needs in a headline; no ETicketsGo market uses cyrillic or greek.
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

# Google Fonts' subset ranges, identical to make-fonts.py so the two families split alike.
RANGES = {
    "latin-ext": "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308,"
    " U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C4, U+2113,"
    " U+2C60-2C7F, U+A720-A7FF",
    "latin": "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308,"
    " U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
}
EXTRA_GLYPHS = {"latin": "U+0300-0301, U+0303, U+0309, U+0323"}

FAMILY = "Bricolage Grotesque"
PREFIX = "bricolage-grotesque"
WEIGHT = "500 800"
# tnum + lnum so a price or a date set in the display face lines up in a column.
FEATURES = "calt,case,ccmp,dnom,frac,kern,liga,lnum,locl,mark,mkmk,numr,pnum,tnum"


def run(*args):
    # A fixed timestamp so a rerun gives byte-identical files (google/fonts commit date).
    env = dict(os.environ, SOURCE_DATE_EPOCH=os.environ.get("SOURCE_DATE_EPOCH", "1772556323"))
    subprocess.run([sys.executable, "-m", *args], check=True, env=env)


def fallback_metrics(ttf):
    """The size-matched Arial face, computed the way next/font does (OS/2 average width)."""
    from fontTools.ttLib import TTFont

    font = TTFont(ttf)
    upm = font["head"].unitsPerEm
    hhea = font["hhea"]
    # Arial's xAvgCharWidth / unitsPerEm, the constant next/font uses for its Arial fallback.
    arial_avg = 904 / 2048
    size_adjust = (font["OS/2"].xAvgCharWidth / upm) / arial_avg
    pct = lambda v: f"{v * 100:.2f}%"  # noqa: E731
    return (
        pct(hhea.ascent / upm / size_adjust),
        pct(abs(hhea.descent) / upm / size_adjust),
        pct(hhea.lineGap / upm / size_adjust),
        pct(size_adjust),
    )


def main(src):
    with tempfile.TemporaryDirectory() as tmp:
        pinned = os.path.join(tmp, "bricolage-pinned.ttf")
        run("fontTools.varLib.instancer", src, "wdth=100", "wght=500:800", "-q", "-o", pinned)
        ascent, descent, line_gap, size = fallback_metrics(pinned)
        css = [
            "/*",
            f"  {FAMILY}: the latin-ext subset (rupee sign, accented capitals), which",
            "  next/font/local does not preload, plus its size-matched fallback face. The latin",
            "  file is loaded by ../src/fonts/brand-display.ts.",
            "  Generated by make-brand-fonts.py; do not edit by hand.",
            "*/",
            "@font-face {",
            f"  font-family: '{FAMILY} Fallback';",
            "  src: local('Arial');",
            f"  ascent-override: {ascent};",
            f"  descent-override: {descent};",
            f"  line-gap-override: {line_gap};",
            f"  size-adjust: {size};",
            "}",
        ]
        for subset in ("latin-ext", "latin"):
            out = f"{PREFIX}-{subset}.woff2"
            unicodes = RANGES[subset] + (", " + EXTRA_GLYPHS[subset] if subset in EXTRA_GLYPHS else "")
            run(
                "fontTools.subset", pinned,
                "--unicodes=" + unicodes.replace(" ", ""),
                "--layout-features=" + FEATURES, "--name-IDs=*", "--name-languages=*",
                "--notdef-outline", "--flavor=woff2",
                "--output-file=" + os.path.join(HERE, out),
            )
            if subset == "latin":
                continue
            css += [
                f"/* {subset} */",
                "@font-face {",
                f"  font-family: '{FAMILY}';",
                "  font-style: normal;",
                f"  font-weight: {WEIGHT};",
                "  font-display: swap;",
                f"  src: url('./{out}') format('woff2');",
                f"  unicode-range: {RANGES[subset]};",
                "}",
            ]
        with open(os.path.join(HERE, f"{PREFIX}.css"), "w", encoding="ascii", newline="\n") as f:
            f.write("\n".join(css) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
